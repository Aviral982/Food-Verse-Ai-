from typing import Optional, List
from fastapi import APIRouter, HTTPException
from pydantic import BaseModel, Field
from backend.services.groq_service import groq_service

router = APIRouter(prefix="/api/meal-planner", tags=["Personalized Meal Planner"])


class MealPlanRequest(BaseModel):
    age: int = Field(..., ge=1, le=120, description="Age in years")
    gender: str = Field(..., description="Gender (e.g. Male, Female, Other, Prefer not to say)")
    height: float = Field(..., gt=30, lt=300, description="Height in centimeters")
    weight: float = Field(..., gt=15, lt=500, description="Weight in kilograms")
    activity_level: str = Field(..., description="Sedentary, Lightly Active, Moderately Active, Very Active, Extremely Active")
    health_conditions: Optional[str] = Field(None, description="Pre-existing conditions, e.g. Hypertension, Diabetes, Thyroid")
    health_goals: str = Field(..., description="Goal: Weight Loss, Muscle Gain, Maintenance, Heart Health, Clean Eating")
    diet_type: str = Field(..., description="Diet type: Balanced, Vegetarian, Vegan, Keto, Mediterranean, Low-Carb, Pescatarian")
    cuisine_preference: Optional[str] = Field("Any", description="Preferred cuisine style")
    allergies: Optional[str] = Field(None, description="Food allergies or intolerances, e.g. Nuts, Dairy, Shellfish, Gluten")
    recent_diet_history: Optional[str] = Field(None, description="Recent eating habits or patterns")
    weight_target: Optional[str] = Field(None, description="Target weight or progress timeframe")


class MealItem(BaseModel):
    name: str = Field(..., description="Dish or meal name")
    calories: int = Field(..., description="Calories in kcal")
    protein_g: int = Field(..., description="Protein in grams")
    carbs_g: int = Field(..., description="Carbohydrates in grams")
    fats_g: int = Field(..., description="Fat in grams")
    ingredients: List[str] = Field(default_factory=list, description="Primary ingredients")
    prep_note: str = Field(..., description="Preparation note or serving tip")


class DailyMeals(BaseModel):
    breakfast: MealItem
    mid_morning_snack: MealItem
    lunch: MealItem
    evening_snack: MealItem
    dinner: MealItem


class MealPlanResponse(BaseModel):
    plan_summary: str = Field(..., description="Overview and caloric strategy for the meal plan")
    target_daily_calories: int = Field(..., description="Target daily caloric intake")
    target_protein_g: int = Field(..., description="Target daily protein in grams")
    target_carbs_g: int = Field(..., description="Target daily carbohydrates in grams")
    target_fats_g: int = Field(..., description="Target daily fat in grams")
    hydration_target_liters: float = Field(..., description="Recommended daily water intake in liters")
    meals: DailyMeals
    weekly_recommendations: List[str] = Field(default_factory=list, description="Weekly habit and consistency advice")
    dietary_tips: List[str] = Field(default_factory=list, description="Nutritional tips and meal prep guidance")
    disclaimer: str = Field(
        default="Medical Advisory: This personalized meal plan is generated by AI for educational and nutritional guidance only. It is not medical or clinical nutrition advice. Consult your physician or registered dietitian before starting any significant dietary change.",
        description="Health and medical disclaimer"
    )


@router.post("/generate", response_model=MealPlanResponse)
async def generate_meal_plan(request: MealPlanRequest):
    """
    Generates a personalized daily meal plan with 5 distinct meal segments (breakfast, mid-morning snack,
    lunch, evening snack, dinner) and complete macronutrient breakdowns based on biometrics, goals, and allergies.
    """
    # Strict allergy check
    allergy_warning = f"CRITICAL: User has documented allergies/intolerances: [{request.allergies}]. DO NOT include any of these foods or their derivatives." if request.allergies else "No allergies reported."

    system_prompt = (
        "You are a licensed clinical dietitian and sports nutritionist in FoodVerse AI. "
        "Create a realistic, scientifically calibrated daily nutrition and meal plan based on the user's biometrics, "
        "activity level, dietary style, and fitness targets. "
        "Strictly obey all allergy constraints. "
        "Provide exactly five structured meals: breakfast, mid_morning_snack, lunch, evening_snack, and dinner. "
        "Calculate realistic macronutrient grams and calorie sums. Output ONLY valid JSON."
    )

    prompt = f"""
Generate a personalized meal plan for this client profile:
- Age: {request.age} years | Gender: {request.gender}
- Height: {request.height} cm | Weight: {request.weight} kg
- Activity Level: {request.activity_level}
- Primary Goal: {request.health_goals}
- Diet Type: {request.diet_type}
- Cuisine Style: {request.cuisine_preference or 'Any'}
- Health Conditions: {request.health_conditions or 'None'}
- Allergies / Intolerances: {allergy_warning}
- Recent Diet History: {request.recent_diet_history or 'Standard balanced diet'}
- Target Weight / Timeline: {request.weight_target or 'Maintain healthy sustainable pace'}

Respond strictly with a JSON object adhering to this schema:
{{
  "plan_summary": "Summary of calorie deficit/surplus strategy tailored to user...",
  "target_daily_calories": 2100,
  "target_protein_g": 140,
  "target_carbs_g": 220,
  "target_fats_g": 70,
  "hydration_target_liters": 2.8,
  "meals": {{
    "breakfast": {{
      "name": "Steel-Cut Oats with Chia, Berries & Whey",
      "calories": 480,
      "protein_g": 32,
      "carbs_g": 62,
      "fats_g": 12,
      "ingredients": ["1 cup cooked steel-cut oats", "1 scoop vanilla protein", "1/2 cup blueberries", "1 tbsp chia seeds"],
      "prep_note": "Simmer oats and fold in protein powder off the heat with fresh berries."
    }},
    "mid_morning_snack": {{
      "name": "Greek Yogurt & Walnuts",
      "calories": 220,
      "protein_g": 18,
      "carbs_g": 10,
      "fats_g": 12,
      "ingredients": ["170g non-fat Greek yogurt", "15g raw walnut halves"],
      "prep_note": "Stir walnuts into cold yogurt with a dash of cinnamon."
    }},
    "lunch": {{
      "name": "Mediterranean Grilled Chicken & Quinoa Bowl",
      "calories": 580,
      "protein_g": 45,
      "carbs_g": 55,
      "fats_g": 18,
      "ingredients": ["150g grilled chicken breast", "1 cup cooked quinoa", "Cucumber", "Cherry tomatoes", "1 tbsp olive oil vinaigrette"],
      "prep_note": "Toss warm quinoa with diced vegetables, sliced chicken, and lemon olive oil."
    }},
    "evening_snack": {{
      "name": "Apple Slices with Almond Butter",
      "calories": 200,
      "protein_g": 5,
      "carbs_g": 24,
      "fats_g": 10,
      "ingredients": ["1 medium Honeycrisp apple", "1 tbsp natural almond butter"],
      "prep_note": "Slice apple and serve with creamy almond butter."
    }},
    "dinner": {{
      "name": "Pan-Seared Salmon with Roasted Asparagus & Sweet Potato",
      "calories": 620,
      "protein_g": 40,
      "carbs_g": 48,
      "fats_g": 26,
      "ingredients": ["170g wild salmon fillet", "1 medium roasted sweet potato", "1 bunch asparagus", "1 tsp olive oil"],
      "prep_note": "Pan-sear salmon skin-side down until crispy; roast asparagus and sweet potato at 200°C."
    }}
  }},
  "weekly_recommendations": [
    "Batch cook quinoa and sweet potatoes on Sunday for quick weekday assembly.",
    "Prioritize drinking 500ml water immediately upon waking."
  ],
  "dietary_tips": [
    "Eat fiber-rich veggies first during main meals to stabilize postprandial glucose.",
    "Keep evening snacks at least 2 hours before bedtime for optimal digestion."
  ],
  "disclaimer": "Medical Advisory: This personalized meal plan is generated by AI for educational and nutritional guidance only. It is not medical or clinical nutrition advice. Consult your physician or registered dietitian before starting any significant dietary change."
}}
"""

    result = await groq_service.generate_json(
        prompt=prompt,
        system_prompt=system_prompt
    )

    try:
        return MealPlanResponse(**result)
    except Exception as e:
        raise HTTPException(
            status_code=502,
            detail=f"Failed to generate structured meal plan: {str(e)}"
        )

